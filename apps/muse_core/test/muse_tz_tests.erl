local_date_time_test_() ->
    [?_assertEqual(Exp, muse_tz:local_date_time(Iso, Zone)) || {Zone, Iso, Exp} <- intl_vectors()].

valid_test_() ->
    [?_assert(muse_tz:valid(<<"America/Los_Angeles">>)),
     ?_assert(muse_tz:valid(<<"UTC">>)),
     ?_assertNot(muse_tz:valid(<<"Mars/Olympus">>)),
     ?_assertNot(muse_tz:valid(<<"../../etc/passwd">>)),
     ?_assertNot(muse_tz:valid(<<"">>)),
     ?_assertNot(muse_tz:valid(undefined))].

fallback_slice_test() ->
    ?assertEqual({<<"2026-10-21">>, <<"00:00">>}, muse_tz:local_date_time(<<"2026-10-21">>, <<"UTC">>)),
    ?assertEqual({<<"garbage">>, <<>>}, muse_tz:local_date_time(<<"garbage">>, <<"UTC">>)).

system_zone_test() ->
    ?assert(muse_tz:valid(muse_tz:system_zone())).
